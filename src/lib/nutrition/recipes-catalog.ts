/**
 * Encuentra la receta clínica correspondiente para un plato o alimento
 */
export function getRecipeForFood(foodName: string, category?: string | null): ClinicalRecipe | null {
  const n = (foodName || '').toLowerCase()

  // Buscar coincidencia exacta por palabras clave
  for (const recipe of CLINICAL_RECIPES) {
    if (recipe.keywords.some((kw) => n.includes(kw))) {
      return recipe
    }
  }

  // Coincidencias por ingredientes principales
  if (n.includes('pollo') || n.includes('pavo')) {
    return CLINICAL_RECIPES.find((r) => r.id === 'rec-pollo-arroz') || null
  }
  if (n.includes('salmón') || n.includes('salmon')) {
    return CLINICAL_RECIPES.find((r) => r.id === 'rec-salmon-brocoli-patata') || null
  }
  if (n.includes('ternera') || n.includes('solomillo') || n.includes('filete')) {
    return CLINICAL_RECIPES.find((r) => r.id === 'rec-solomillo-boniato') || null
  }
  if (n.includes('lenteja') || n.includes('garbanzo') || n.includes('legumbre')) {
    return CLINICAL_RECIPES.find((r) => r.id === 'rec-lentejas-estofadas') || null
  }
  if (n.includes('merluza') || n.includes('bacalao')) {
    return CLINICAL_RECIPES.find((r) => r.id === 'rec-merluza-pure') || null
  }
  if (n.includes('avena') || n.includes('porridge')) {
    return CLINICAL_RECIPES.find((r) => r.id === 'rec-porridge-avena') || null
  }
  if (n.includes('huevo') || n.includes('tostada')) {
    return CLINICAL_RECIPES.find((r) => r.id === 'rec-tostada-huevo-poche') || null
  }
  if (n.includes('pasta') || n.includes('macarron') || n.includes('espagueti')) {
    return CLINICAL_RECIPES.find((r) => r.id === 'rec-pasta-picada-setas') || null
  }
  if (n.includes('dorada') || n.includes('lubina')) {
    return CLINICAL_RECIPES.find((r) => r.id === 'rec-dorada-horno-patata') || null
  }
  if (n.includes('sepia') || n.includes('calamar') || n.includes('gamba')) {
    return CLINICAL_RECIPES.find((r) => r.id === 'rec-sepia-esparragos') || null
  }
  if (n.includes('tofu') || n.includes('soja') || n.includes('tempeh')) {
    return CLINICAL_RECIPES.find((r) => r.id === 'rec-tofu-wok-verduras') || null
  }
  if (n.includes('yogur') || n.includes('kéfir') || n.includes('kefir') || n.includes('queso fresco')) {
    return CLINICAL_RECIPES.find((r) => r.id === 'rec-bowl-yogur-fruta') || null
  }

  return null
}
